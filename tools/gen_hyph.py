import sys
args = [a for a in sys.argv[1:] if a != "--pion"]
d = args[0]
pats = open(d + "/hyph-en-us.pat.txt").read().split()
exc = open(d + "/hyph-en-us.hyp.txt").read().split()
def chunks(words):
    line, out = "", []
    for w in words:
        if len(line) + len(w) + 1 > 110:
            out.append(line); line = ""
        line += w + " "
    out.append(line)
    return out
def pchunks(words):
    cs = [l.rstrip() for l in chunks(words)]
    return ["\"" + c + "\\n\"" + (" +" if i + 1 < len(cs) else "") for i, c in enumerate(cs)]
out = ["// Generated by tools/gen_hyph.py --pion from hyph-utf8's hyph-en-us (Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken;",
       "// copying and distribution, with or without modification, are permitted in any medium without royalty provided",
       "// the copyright notice and this notice are preserved). Do not edit.", "",
       "let en_patterns : String ="] + pchunks(pats) + ["",
       "let en_exceptions : String ="] + pchunks(exc) + [""]
open("pion/packages/layout/hyph_tables.pion", "w").write("\n".join(out))
