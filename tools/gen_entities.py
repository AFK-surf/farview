#!/usr/bin/env python3
"""Generates pion/packages/html/entities.pion from pinned WHATWG entities.json.

Source: https://html.spec.whatwg.org/entities.json
License of WHATWG data when incorporated into source: BSD-3-Clause
(see LICENSES/WHATWG-Encoding-LICENSE.txt and THIRD_PARTY_NOTICES.md).

Usage:
  python3 tools/gen_entities.py [--pion] [--from-file <path>]
"""
import argparse
import hashlib
import json
import os
import sys
import urllib.request

WHATWG_ENTITIES_URL = "https://html.spec.whatwg.org/entities.json"
WHATWG_ENTITIES_SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"


def pion_esc(s: str) -> str:
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\0":
            out.append("\\0")
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate pion/packages/html/entities.pion from WHATWG entities.json")
    parser.add_argument("--pion", action="store_true", help="Accepted for compatibility")
    parser.add_argument("--from-file", help="Read entities.json from a local file instead of downloading")
    parser.add_argument("--allow-unverified", action="store_true", help="Skip SHA-256 check against pinned WHATWG snapshot")
    args = parser.parse_args()

    if args.from_file:
        raw = open(args.from_file, "rb").read()
    else:
        with urllib.request.urlopen(WHATWG_ENTITIES_URL, timeout=30) as resp:
            raw = resp.read()

    digest = hashlib.sha256(raw).hexdigest()
    if not args.allow_unverified and digest != WHATWG_ENTITIES_SHA256:
        sys.exit(
            f"SHA-256 mismatch for WHATWG entities.json: got {digest}, expected {WHATWG_ENTITIES_SHA256}"
        )

    data = json.loads(raw.decode("utf-8"))
    entities = {}
    for k, v in data.items():
        name = k[1:] if k.startswith("&") else k
        entities[name] = v["characters"]

    out_path = "pion/packages/html/entities.pion"
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    out = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Generated by tools/gen_entities.py from WHATWG HTML Standard named character references.",
        f"// Source: {WHATWG_ENTITIES_URL} (SHA-256: {digest})",
        "// Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft). Do not edit.",
        "",
        "struct EntityPair {",
        "  name : String",
        "  value : String",
        "}",
        "",
        "let ENTITY_LIST : Array[EntityPair] = [",
    ]
    for k in sorted(entities):
        out.append('  EntityPair::{ name: "%s", value: "%s" },' % (pion_esc(k), pion_esc(entities[k])))
    out += ["]", ""]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
