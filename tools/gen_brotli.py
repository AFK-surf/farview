# Writes pion/packages/brotli/tables.pion:
# RFC 7932's dictionary, transforms and context lookup, taken from google/brotli's C
# sources (MIT):
#   python3 tools/gen_brotli.py [--pion] <dir holding dictionary.bin, transform.c, context.c>
import base64, os, re, sys

def pion_str(b):
    out = []
    for c in b:
        if c == 0x22:
            out.append('\\"')
        elif c == 0x5c:
            out.append('\\\\')
        elif c == 0x0a:
            out.append('\\n')
        elif c == 0x0d:
            out.append('\\r')
        elif c == 0x09:
            out.append('\\t')
        elif c == 0x00:
            out.append('\\0')
        else:
            out.append(chr(c))
    # decode latin1 bytes back as utf-8 text so multi-byte utf-8 (e.g. \xc2\xa0) is emitted raw
    raw_bytes = bytearray()
    for ch in out:
        if len(ch) > 1:
            raw_bytes.extend(ch.encode("ascii"))
        else:
            raw_bytes.append(ord(ch))
    return '"' + raw_bytes.decode("utf-8") + '"'

def write_pion(dict_b64, lut_b64, transform_rows, out_path="pion/packages/brotli/tables.pion"):
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    out = [
        "// Generated by tools/gen_brotli.py --pion from google/brotli (MIT). Do not edit.",
        "",
        "struct Transform {",
        "  prefix : String",
        "  kind : Int",
        "  suffix : String",
        "}",
        "",
        'let DICTIONARY_B64 : String = "' + dict_b64 + '"',
        "",
        'let CONTEXT_LUT_B64 : String = "' + lut_b64 + '"',
        "",
        "let TRANSFORMS : Array[Transform] = [",
    ]
    for p_bytes, kind, s_bytes in transform_rows:
        out.append(
            "  Transform::{ prefix: %s, kind: %d, suffix: %s },"
            % (pion_str(p_bytes), kind, pion_str(s_bytes))
        )
    out += ["]", ""]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))

args = [a for a in sys.argv[1:] if a != "--pion"]
d = args[0]

dictionary = open(d + "/dictionary.bin", "rb").read()
assert len(dictionary) == 122784
ctx = open(d + "/context.c").read()
body = ctx[ctx.index("[2048] = {") + 10:]
body = re.sub(r"/\*.*?\*/", "", body[:body.index("};")], flags=re.S)
lut = bytes(int(x) for x in re.findall(r"\d+", body))
assert len(lut) == 2048
tr = open(d + "/transform.c").read()
ps = tr[tr.index("kPrefixSuffix[217] ="):tr.index(";", tr.index("kPrefixSuffix[217] ="))]
ps = re.sub(r"/\*.*?\*/", "", ps, flags=re.S)
raw = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', ps))
prefix_suffix = raw.encode("latin1").decode("unicode_escape").encode("latin1") + b"\0"
assert len(prefix_suffix) == 217, len(prefix_suffix)
m = tr[tr.index("kPrefixSuffixMap[50] = {") + 24:]
pmap = [int(x, 16) for x in re.findall(r"0x[0-9A-F]+", m[:m.index("}")])]
kinds = {"IDENTITY": 0, "UPPERCASE_FIRST": 10, "UPPERCASE_ALL": 11}
for k in range(1, 10):
    kinds["OMIT_LAST_%d" % k] = k
    kinds["OMIT_FIRST_%d" % k] = 11 + k
t = tr[tr.index("kTransformsData[] = {"):]
t = t[:t.index("};")]
rows = re.findall(r"(\d+), BROTLI_TRANSFORM_(\w+), (\d+)", t)
assert len(rows) == 121
def piece(i):
    at = pmap[i]
    n = prefix_suffix[at]
    return prefix_suffix[at + 1:at + 1 + n]
trows = [(piece(int(p)), kinds[k], piece(int(s))) for p, k, s in rows]
write_pion(base64.b64encode(dictionary).decode(), base64.b64encode(lut).decode(), trows)
