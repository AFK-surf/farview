# Writes pion/packages/page_js/{prelude,editing}.pion from js/prelude.js and js/editing.js
# (--pion flag is accepted for compatibility).
import os
import shutil
import subprocess
import sys


def pion_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
    )


def emit_pion_string_file(src_path: str, dst_path: str, fn_name: str, chunk_lines: int = 80) -> None:
    raw = open(src_path, "r", encoding="utf-8").read()
    src_lines = raw.splitlines(keepends=True)
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    chunks = []
    for i in range(0, len(src_lines), chunk_lines):
        chunks.append("".join(src_lines[i : i + chunk_lines]))
    out_lines = [
        f"// Generated by tools/gen_prelude.py --pion from {src_path}. Do not edit.",
        "",
        f"pub fn {fn_name}() -> String {{",
        "  let parts : Array[String] = [",
    ]
    for c in chunks:
        out_lines.append(f'    "{pion_escape(c)}",')
    out_lines += [
        "  ]",
        '  parts.join("")',
        "}",
        "",
    ]
    open(dst_path, "w", encoding="utf-8").write("\n".join(out_lines))


emit_pion_string_file("js/prelude.js", "pion/packages/page_js/prelude.pion", "prelude_js")
emit_pion_string_file("js/editing.js", "pion/packages/page_js/editing.pion", "editing_js")

# A syntax error in the prelude leaves every page without a DOM: say so here, not later.
# (where node is not installed, the check is left to the machine the prelude is written on)
for f in ["js/prelude.js", "js/editing.js"]:
    r = subprocess.run(["node", "--check", f], capture_output=True, text=True) if shutil.which("node") else None
    if r is not None and r.returncode != 0:
        sys.exit(f + ": " + r.stderr.strip())
